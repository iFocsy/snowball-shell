/* The i-th scheme's name, or NULL past the last. */
LPCSTR SchemesName(int i)
{
    return i < NSCHEMES ? schemes[i].name : NULL;
}

/* Its group in the Theme Manager. */
LPCSTR SchemesGroup(int i)
{
    return i < NSCHEMES ? schemes[i].group : NULL;
}

/* A scheme of Snowball's by name: its colours, or NULL. */
LPCSTR SchemesColors(LPCSTR name)
{
    int i;

    for (i = 0; i < NSCHEMES; i++)
        if (!lstrcmpi(schemes[i].name, name))
            return schemes[i].colors;
    return NULL;
}

/* One of Windows 3.1's own, not offered. */
BOOL SchemesOld(LPCSTR name)
{
    int i;

    for (i = 0; i < sizeof old / sizeof old[0]; i++)
        if (!lstrcmpi(old[i], name))
            return TRUE;
    return FALSE;
}
